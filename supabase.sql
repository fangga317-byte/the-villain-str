create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Pengguna',
  email text unique,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'name','Pengguna'), new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(12,2) not null default 0 check (price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id),
  quantity integer not null default 1 check (quantity > 0),
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'Menunggu Pembayaran'
    check (status in ('Menunggu Pembayaran','Menunggu Verifikasi','Diproses','Selesai','Ditolak')),
  payment_note text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

create policy "profiles read own or admin" on public.profiles for select to authenticated
using (id = auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
create policy "users update own name" on public.profiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid() and role = (select p.role from public.profiles p where p.id=auth.uid()));

create policy "products visible" on public.products for select to authenticated using (active = true or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
create policy "admins insert products" on public.products for insert to authenticated
with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
create policy "admins update products" on public.products for update to authenticated
using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))
with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

create policy "users read own orders or admin" on public.orders for select to authenticated
using (user_id = auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
create policy "users create own orders" on public.orders for insert to authenticated
with check (user_id = auth.uid());
create policy "users submit payment note; admins update status" on public.orders for update to authenticated
using (user_id = auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))
with check (user_id = auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

